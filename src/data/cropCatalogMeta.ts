export function matchAgmarknetCommodityToCropId(commodityName: string): string | null {
  const normalized = commodityName.trim().toLowerCase();
  if (!normalized) return null;
  for (const crop of CROP_CATALOG_META) {
    if (crop.name.toLowerCase() === normalized) return crop.id;
    if (crop.agmarknetAliases.some((alias) => normalized === alias || normalized.includes(alias))) {
      return crop.id;
    }
  }
  return null;
}
