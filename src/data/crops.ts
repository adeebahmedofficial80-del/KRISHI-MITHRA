const UPDATED_DATE = '18 Nov 2026';

function buildHistorySeries(
  baseModal: number,
  baseMin: number,
  baseMax: number,
  trendPct: number,
  days: number,
): PriceHistoryPoint[] {
  const points: PriceHistoryPoint[] = [];
  const endDate = new Date('2026-11-18T00:00:00Z');
  const startFactor = 1 - trendPct / 100;
  for (let i = days - 1; i >= 0; i--) {
    const progress = days === 1 ? 1 : (days - 1 - i) / (days - 1);
    const wave = Math.sin((days - 1 - i) * 0.75) * 0.03 + Math.cos((days - 1 - i) * 0.35) * 0.015;
    const factor = startFactor + (1 - startFactor) * progress + (i === 0 ? 0 : wave);
    const modal = Math.max(4, Math.round(baseModal * factor));
    const minSpread = Math.max(2, Math.round((baseModal - baseMin) * (0.95 + wave * 0.5)));
    const maxSpread = Math.max(2, Math.round((baseMax - baseModal) * (0.95 - wave * 0.5)));
    const min = i === 0 ? baseMin : Math.max(2, modal - minSpread);
    const max = i === 0 ? baseMax : modal + maxSpread;

    const d = new Date(endDate);
    d.setUTCDate(endDate.getUTCDate() - i);
    const iso = d.toISOString().slice(0, 10);
    const label = d.toLocaleDateString('en-IN', {day: 'numeric', month: 'short', timeZone: 'UTC'});

    points.push({
      date: iso,
      label,
      modal: i === 0 ? baseModal : modal,
      min,
      max,
    });
  }
  return points;
}

