const CATALOG_REFERENCE_DATE = 'Reference baseline';

function buildReferenceHistory(modal: number, min: number, max: number, days: number): PriceHistoryPoint[] {
  const points: PriceHistoryPoint[] = [];
  const today = new Date();
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(today.getDate() - i);
    const iso = d.toISOString().slice(0, 10);
    const label = d.toLocaleDateString('en-IN', {day: 'numeric', month: 'short'});
    points.push({
      date: iso,
      label,
      modal,
      min,
      max,
      modalQuintal: modal * 100,
    });
  }
  return points;
}

function buildReferenceComparisons(
  modal: number,
  min: number,
  max: number,
): MarketPriceEntry[] {
  const defs = [
    {id: 'bengaluru-apmc', name: 'Bengaluru APMC', district: 'Bengaluru Urban', state: 'Karnataka', dist: 28, off: 0},
    {id: 'hoskote-apmc', name: 'Hoskote APMC', district: 'Bengaluru Rural', state: 'Karnataka', dist: 22, off: -1},
    {id: 'mysuru-apmc', name: 'Mysuru APMC', district: 'Mysuru', state: 'Karnataka', dist: 145, off: 1},
  ];
  return defs.map((m) => {
    const mPrice = Math.max(6, modal + m.off);
    return {
      marketId: m.id,
      marketName: m.name,
      district: m.district,
      state: m.state,
      modalPrice: mPrice,
      minPrice: Math.max(4, min + m.off),
      maxPrice: max + m.off,
      modalPriceQuintal: mPrice * 100,
      minPriceQuintal: Math.max(4, min + m.off) * 100,
      maxPriceQuintal: (max + m.off) * 100,
      trendPercent: null,
      arrivalDate: CATALOG_REFERENCE_DATE,
      distanceKm: m.dist,
      priceType: 'Wholesale Mandi',
      dataSource: 'catalog_reference',
    };
  });
}

